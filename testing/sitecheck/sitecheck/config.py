@dataclass(frozen=True)
class VisitTiming:
    """How both engines visit a page, in seconds: one definition, so the captures
    being compared are taken under the same conditions. servo.ServoTiming adds what
    only a servoshell process needs."""

    page_load_timeout: float = 45.0  # The load event; on timeout the page is probed anyway.
    script_timeout: float = 20.0  # Each script (scroll, probe) and, in Chromium, the screenshot.
    settle: float = 3.0  # After navigation, for late scripts and fonts.
    scroll_pause: float = 1.0  # After each scroll, for lazy-loaded content.
    wall_clock: float = 90.0  # Hard limit for the whole page; exceeding it is a hang.


DEFAULT_VISIT_TIMING = VisitTiming()

# What the engine processes (servoshell, Playwright's driver and Chromium) inherit
# from the harness's environment: only what a headless browser needs. In particular
# the Hister token (HISTER_TOKEN may be set in the environment) never reaches an
# engine that runs arbitrary web content.
_CHILD_ENV_NAMES = frozenset(
    {"PATH", "HOME", "USER", "LOGNAME", "TMPDIR", "LANG", "LANGUAGE", "TZ"}
)
_CHILD_ENV_PREFIXES = ("LC_", "XDG_", "FONTCONFIG_")

# Servo's own Android user agent: the `UserAgentPlatform::Android` branch of
# `to_user_agent_string` in components/config/prefs.rs of the Servo checkout. Both
# engines send it so servers return the same markup and differences come from the
# engine. Update it when that branch changes (for example the Firefox version).
USER_AGENT_TEMPLATE = "Mozilla/5.0 (Android 10; Mobile; rv:153.0) Servo/{version} Firefox/153.0"

# Cargo package versions are semver; anything else would end up verbatim in a header.
_VERSION_PATTERN = re.compile(r"[0-9]+\.[0-9]+\.[0-9]+(?:[-+][0-9A-Za-z.+-]+)?")
_CARGO_MANIFEST_NAME = "Cargo.toml"
_CARGO_TARGET_DIR_NAME = "target"

_COMMENT_PREFIX = "#"
_QUOTES = ("'", '"')


class ConfigError(Exception):
    """The configuration or the environment is unusable; the CLI exits with status 2."""


class RunLockedError(ConfigError):
    """Another site check run holds the data directory's lock."""


@dataclass(frozen=True, repr=False)
class HisterSettings:
    """Where to reach Hister and how to authenticate. The token never appears in repr()."""

    url: str
    token: str

    def __repr__(self) -> str:
        return f"HisterSettings(url={self.url!r}, token=<redacted>)"

    __str__ = __repr__


def child_environment(environ: Mapping[str, str] | None = None) -> dict[str, str]:
    """The allowlisted environment for an engine process (see _CHILD_ENV_NAMES)."""
    env = os.environ if environ is None else environ
    return {
        name: value
        for name, value in env.items()
        if name in _CHILD_ENV_NAMES or name.startswith(_CHILD_ENV_PREFIXES)
    }


def scrub_secrets(environ: MutableMapping[str, str]) -> None:
    """Remove the Hister settings from `environ` (normally os.environ) once read.

    Child processes then cannot inherit the token, whichever way they are started
    (Playwright's driver copies os.environ when it starts).
    """
    for name in (HISTER_URL_KEY, HISTER_TOKEN_KEY):
        environ.pop(name, None)


def data_dir(environ: Mapping[str, str] | None = None) -> Path:
    """The private data directory; it is not created here (see `ensure_private_dir`)."""
    env = os.environ if environ is None else environ
    return _dir_from_env(env, DATA_DIR_ENV, _DEFAULT_DATA_DIR)


def config_dir(environ: Mapping[str, str] | None = None) -> Path:
    env = os.environ if environ is None else environ
    return _dir_from_env(env, CONFIG_DIR_ENV, _DEFAULT_CONFIG_DIR)


def ensure_private_dir(path: Path) -> Path:
    """Create `path` with mode 0700, or tighten it to 0700 if it already exists.

    Raises ConfigError when the path is not a directory or belongs to another user,
    since history-derived files would then be readable by someone else.
    """
    try:
        path.mkdir(mode=PRIVATE_DIR_MODE, parents=True, exist_ok=True)
        info = path.stat()
    except FileExistsError as error:
        raise ConfigError(f"{path} exists and is not a directory") from error
    except OSError as error:
        raise ConfigError(f"cannot create {path}: {error.strerror}") from error

    if not stat.S_ISDIR(info.st_mode):
        raise ConfigError(f"{path} exists and is not a directory")
    if info.st_uid != os.getuid():
        raise ConfigError(f"{path} belongs to another user; choose a directory you own")
    if stat.S_IMODE(info.st_mode) != PRIVATE_DIR_MODE:
        # mkdir's mode is filtered by the umask, and an existing directory keeps its
        # mode, so set it explicitly either way.
        os.chmod(path, PRIVATE_DIR_MODE)
    return path


def write_private_file(path: Path, content: bytes) -> None:
    """Replace `path` with `content`, readable by the owner only (0600).

    The content goes to a new temporary file next to `path`, which is then renamed
    over it, so neither an existing file's looser mode nor a symlink at `path` is
    reused, and a reader never sees half a file. The content is synced before the
    rename, so a crash cannot leave an empty file under the final name (macOS's
    fsync does not flush the drive's own cache).
    """
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(temporary)
        raise


def state_db_path(data: Path) -> Path:
    return data / STATE_DB_NAME


def run_dir(data: Path, run_id: str) -> Path:
    if not _RUN_ID_PATTERN.fullmatch(run_id):
        raise ValueError(f"invalid run id {run_id!r}")
    return data / RUNS_DIR_NAME / run_id


def page_key(url: str) -> str:
    """A stable directory name for a page that does not reveal its URL."""
    return hashlib.sha256(url.encode("utf-8")).hexdigest()[:_PAGE_KEY_LENGTH]


def page_dir(run: Path, url: str) -> Path:
    """Where one page's artifacts go inside a run directory (see `run_dir`)."""
    return run / PAGES_DIR_NAME / page_key(url)


def signature_key(data: Path) -> bytes:
    """The private key that tags sites in symptom signatures, created on first use.

    It stays in the data directory, so a tag quoted outside cannot be traced back
    to a site by hashing candidate names. A key file that is too short raises
    ConfigError rather than being replaced: a new key renames the site tag of every
    stored issue signature, so wontfix and upstream decisions would stop matching.
    """
    path = data / SIGNATURE_KEY_NAME
    try:
        key = path.read_bytes()
    except FileNotFoundError:
        key = secrets.token_bytes(_SIGNATURE_KEY_BYTES)
        write_private_file(path, key)
        return key
    except OSError as error:
        raise ConfigError(f"cannot read {path}: {error.strerror}") from error
    if len(key) < _SIGNATURE_KEY_BYTES:
        raise ConfigError(
            f"{path} is damaged ({len(key)} bytes, expected at least {_SIGNATURE_KEY_BYTES}); "
            "restore it from a backup, or delete it to start a new key, which gives "
            "existing site-scoped issues new signatures"
        )
    return key


def reference_cache_dir(data: Path, url: str) -> Path:
    return data / REFERENCE_CACHE_DIR_NAME / page_key(url)


@contextmanager
def run_lock(data: Path) -> Iterator[None]:
    """Hold the data directory's single-run lock, or raise RunLockedError at once.

    Two runs would fight over the one servoshell and Chromium the machine can afford,
    and over the store. flock releases the lock when the process dies, so a crashed
    run never leaves a stale lock behind.
    """
    path = data / LOCK_NAME
    try:
        fd = os.open(path, os.O_RDWR | os.O_CREAT, _PRIVATE_FILE_MODE)
    except OSError as error:
        raise ConfigError(f"cannot open the lock file {path}: {error.strerror}") from error

    try:
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as error:
            if error.errno not in (errno.EWOULDBLOCK, errno.EAGAIN):
                raise ConfigError(f"cannot lock {path}: {error.strerror}") from error
            holder = _read_lock_holder(fd)
            raise RunLockedError(
                f"another site check run{holder} is using {data}; wait for it to finish"
            ) from None

        # Recorded only to make the error above more helpful; the lock is the flock.
        os.ftruncate(fd, 0)
        os.write(fd, f"{os.getpid()}\n".encode("ascii"))
        yield
    finally:
        os.close(fd)


def load_hister_settings(
    path: Path | None = None,
    environ: Mapping[str, str] | None = None,
    warnings: TextIO | None = None,
) -> HisterSettings | None:
    """Read the Hister URL and token from `hister.env`, overridden by the environment.

    Returns None when either value is missing or empty (Hister is not configured).
    The file holds `KEY=VALUE` lines, whole-line `#` comments and blank lines; a value
    may be wrapped in matching single or double quotes, which are removed, and
    surrounding whitespace is ignored. Nothing is expanded or executed. A non-empty
    environment variable of the same name wins over the file. Messages never include
    values, since one of them is the token.
    """
    env = os.environ if environ is None else environ
    out = sys.stderr if warnings is None else warnings
    file_path = config_dir(env) / HISTER_ENV_NAME if path is None else path

    values = _read_env_file(file_path, out)
    for key in (HISTER_URL_KEY, HISTER_TOKEN_KEY):
        override = env.get(key, "").strip()
        if override:
            values[key] = override

    url = values.get(HISTER_URL_KEY, "")
    token = values.get(HISTER_TOKEN_KEY, "")
    if not url or not token:
        return None
    return HisterSettings(url=url, token=token)


def user_agent(servo_version: str) -> str:
    if not _VERSION_PATTERN.fullmatch(servo_version):
        raise ValueError(f"not a Servo version: {servo_version!r}")
    return USER_AGENT_TEMPLATE.format(version=servo_version)


def servo_version(checkout: Path) -> str:
    """The version in the Servo checkout's root Cargo.toml, for the user agent.

    Uses `[workspace.package] version` (Servo's layout), else `[package] version`.
    """
    manifest = checkout / _CARGO_MANIFEST_NAME
    try:
        with manifest.open("rb") as file:
            document = tomllib.load(file)
    except FileNotFoundError as error:
        raise ConfigError(
            f"no {_CARGO_MANIFEST_NAME} in {checkout}; is it a Servo checkout?"
        ) from error
    except OSError as error:
        raise ConfigError(f"cannot read {manifest}: {error.strerror}") from error
    except tomllib.TOMLDecodeError as error:
        raise ConfigError(f"{manifest} is not valid TOML: {error}") from error

    candidates = (
        document.get("workspace", {}).get("package", {}).get("version"),
        document.get("package", {}).get("version"),
    )
    # A member crate may say `version.workspace = true`, which parses as a table.
    version = next((value for value in candidates if isinstance(value, str)), None)
    if version is None:
        raise ConfigError(f"{manifest} declares no package version")
    if not _VERSION_PATTERN.fullmatch(version):
        raise ConfigError(f"{manifest} declares an unexpected version {version!r}")
    return version


def default_servo_binary(environ: Mapping[str, str] | None = None) -> Path | None:
    """The servoshell to test when the command line names none.

    `$COMBRAY_SITECHECK_SERVO` when set (returned even if missing, so the caller
    reports the bad setting), else the default checkout's build if it exists, else None.
    """
    env = os.environ if environ is None else environ
    configured = env.get(SERVO_BINARY_ENV, "").strip()
    if configured:
        return _expand_user(configured, env)

    default = _home(env) / _DEFAULT_SERVO_BINARY
    if not default.is_file():
        return None
    return default


def servo_checkout(binary: Path) -> Path:
    """The Servo checkout a servoshell binary was built in: the parent of `target/`."""
    for parent in binary.resolve().parents:
        if parent.name == _CARGO_TARGET_DIR_NAME:
            return parent.parent
    raise ConfigError(f"{binary} is not inside a Cargo target directory; cannot find its checkout")


def deny_list_path(config: Path) -> Path:
    return config / DENY_LIST_NAME


