def load_deny_list(path: Path) -> tuple[str, ...]:
    """Entries of the optional deny list, normalized for `urlpolicy.classify`.

    One host suffix ("example.com" also denies "a.example.com") or http(s) URL prefix
    per line; blank lines and `#` comment lines are ignored. A missing file means an
    empty list.
    """
    entries = []
    for number, line in _data_lines(path):
        try:
            entries.append(urlpolicy.normalize_deny_entry(line))
        except ValueError as error:
            raise ConfigError(
                f"{path}:{number}: expected a host suffix or an http(s) URL prefix ({error})"
            ) from None
    return tuple(entries)


def load_seed_urls(path: Path) -> tuple[str, ...]:
    """URLs listed one per line, ignoring blank lines and `#` comments.

    They are returned as written: the URL policy decides which ones are eligible. A
    missing file means no seeds.
    """
    return tuple(line for _, line in _data_lines(path))


def _dir_from_env(env: Mapping[str, str], name: str, default: Path) -> Path:
    configured = env.get(name, "").strip()
    if configured:
        return _expand_user(configured, env)
    return _home(env) / default


def _home(env: Mapping[str, str]) -> Path:
    home = env.get("HOME", "").strip()
    if home:
        return Path(home)
    return Path.home()


def _expand_user(value: str, env: Mapping[str, str]) -> Path:
    if value == "~" or value.startswith("~/"):
        return _home(env) / value[2:]
    return Path(value)


def _read_lock_holder(fd: int) -> str:
    try:
        content = os.pread(fd, 32, 0).decode("ascii").strip()
    except (OSError, UnicodeDecodeError):
        return ""
    if not content.isdigit():
        return ""
    return f" (pid {content})"


def _read_env_file(path: Path, warnings: TextIO) -> dict[str, str]:
    """Parse `path` as KEY=VALUE data. A missing file yields no values."""
    try:
        mode = path.stat().st_mode
    except FileNotFoundError:
        return {}
    except OSError as error:
        raise ConfigError(f"cannot read {path}: {error.strerror}") from error

    if mode & _SHARED_PERMISSION_BITS:
        print(
            f"warning: {path} holds a token but other users can access it "
            f"(mode {stat.S_IMODE(mode):04o}); run: chmod 600 {path}",
            file=warnings,
        )

    values: dict[str, str] = {}
    for number, line in _data_lines(path):
        key, separator, raw_value = line.partition("=")
        key = key.strip()
        # Messages name the line, never its text: a malformed line may be the token.
        if not separator or not key:
            raise ConfigError(f"{path}:{number}: expected KEY=VALUE")
        if key not in (HISTER_URL_KEY, HISTER_TOKEN_KEY):
            print(
                f"warning: {path}:{number}: ignoring a key other than "
                f"{HISTER_URL_KEY} or {HISTER_TOKEN_KEY}",
                file=warnings,
            )
            continue
        if key in values:
            raise ConfigError(f"{path}:{number}: {key} is set twice")
        values[key] = _unquote(raw_value.strip()).strip()
    return values


def _data_lines(path: Path) -> Iterator[tuple[int, str]]:
    """Non-blank, non-comment lines of a small text file, stripped, with line numbers."""
    try:
        text = path.read_text(encoding="utf-8-sig")
    except FileNotFoundError:
        return
    except UnicodeDecodeError as error:
        raise ConfigError(f"{path} is not UTF-8 text") from error
    except OSError as error:
        raise ConfigError(f"cannot read {path}: {error.strerror}") from error

    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith(_COMMENT_PREFIX):
            continue
        yield number, line


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] and value[0] in _QUOTES:
        return value[1:-1]
    return value
