#!/usr/bin/env python3
"""Generate the Android adaptive launcher icon from media-sources/icon.png (the source of truth).

    python3 scripts/generate-launcher-icons.py

The artwork's background is one flat color, so the adaptive icon is:
- background: that color, sampled from the artwork's corners;
- foreground: the whole, unmodified artwork scaled to ARTWORK_DP of the 108 dp canvas.
The artwork's edge then lies outside the 72 dp area launchers show, so no edge is ever
visible, and the letter (about 76 % of the artwork) stays inside the 66 dp safe zone. The
launcher's own mask (circle, squircle, square) is the device's choice.
Requires Pillow. Rerun after changing the source artwork, then commit the outputs.
"""

import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "media-sources/icon.png"
RES = ROOT / "app/src/main/res"
CANVAS_DP = 108
ARTWORK_DP = 86
DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}


def background_color(image):
    corners = [image.getpixel((x, y)) for x in (2, image.width - 3) for y in (2, image.height - 3)]
    return tuple(round(sum(c[i] for c in corners) / len(corners)) for i in range(3))


def main():
    artwork = Image.open(SOURCE).convert("RGB")
    color = background_color(artwork)

    for density, scale in DENSITIES.items():
        canvas_px = round(CANVAS_DP * scale)
        artwork_px = round(ARTWORK_DP * scale)
        foreground = Image.new("RGBA", (canvas_px, canvas_px), (0, 0, 0, 0))
        resized = artwork.resize((artwork_px, artwork_px), Image.LANCZOS)
        offset = (canvas_px - artwork_px) // 2
        foreground.paste(resized, (offset, offset))
        out = RES / f"mipmap-{density}/ic_launcher_foreground.png"
        out.parent.mkdir(parents=True, exist_ok=True)
        foreground.save(out, optimize=True)

    values = RES / "values/ic_launcher_background.xml"
    values.parent.mkdir(parents=True, exist_ok=True)
    values.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/generate-launcher-icons.py from media-sources/icon.png. -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">#{color[0]:02X}{color[1]:02X}{color[2]:02X}</color>\n'
        "</resources>\n"
    )
    print(f"background #{color[0]:02X}{color[1]:02X}{color[2]:02X}; foreground in {len(DENSITIES)} densities")


if __name__ == "__main__":
    main()
